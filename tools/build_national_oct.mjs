const BASE_DATES = ["2011-03-31", "2016-01-01", "2021-01-01"];
const FALLBACK_2025 = "2026-01-01";
const INDEX = { 2015: 1, 2020: 2, 2025: 3 };

async function ensureTokyoCsv(year) {
  const dest = path.join(RAW, `tokyo_juki_${year}-10.csv`);
  if (fs.existsSync(dest) && fs.statSync(dest).size > 1000) return dest;
  fs.mkdirSync(RAW, { recursive: true });
  const res = await fetch(TOKYO[year].url, { headers: { "User-Agent": "Mozilla/5.0" } });
  if (!res.ok) throw new Error(`東京都CSVの取得に失敗 (${year}): HTTP ${res.status}`);
  fs.writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
  return dest;
}

function readTokyoWards(file) {
  // 数値列はASCIIなので、日本語ヘッダのデコードは不要。2015/2025は階層4、2020は階層5。
  const rows = fs.readFileSync(file, "latin1").split(/\r?\n/).map((l) => l.split(","));
  const wards = new Map();
  for (const r of rows) {
    if ((r[0] === "4" || r[0] === "5") && /^131\d\d$/.test(r[1]) && !wards.has(r[1])) {
      wards.set(r[1], Number(r[3]));
    }
  }
  const sum = [...wards.values()].reduce((a, b) => a + b, 0);
  const totalRow = rows.find((r) => r[1] === "13100" && Number(r[3]) > 0);
  if (wards.size !== 23) throw new Error(`23区の行が${wards.size}件`);
  if (!totalRow || Number(totalRow[3]) !== sum) throw new Error(`23区合計 ${sum} が区部と不一致`);
  return sum;
}

async function main() {
  const tokyo = {};
  for (const year of Object.keys(TOKYO)) {
    const file = await ensureTokyoCsv(year);
    const sum = readTokyoWards(file);
    if (sum !== TOKYO[year].value) throw new Error(`東京${year}年の値が想定と不一致: ${sum}`);
    tokyo[year] = [sum, TOKYO[year].date];
  }

  const jpath = path.join(ROOT, "data", "national.json");
  const out = JSON.parse(fs.readFileSync(jpath, "utf8"));
  if (out.length !== 47) throw new Error(`47地点ではなく${out.length}件`);
  let changed = 0;
  for (const r of out) {
    r.jukiDate = [...BASE_DATES, FALLBACK_2025];
    const table = r.code === "13100" ? tokyo : (OCT[r.code] || {});
    for (const year of [2015, 2020, 2025]) {
      const e = table[year];
      if (!e) continue;
      const idx = INDEX[year];
      const old = r.juki[idx];
      if (old && Math.abs(e[0] - old) / old > 0.01) {
        throw new Error(`${r.city} ${year}: 値が1%以上違う ${old} -> ${e[0]}`);
      }
      r.juki[idx] = e[0];
      r.jukiDate[idx] = e[1];
      if (e[0] !== old) changed++;
    }
  }
  fs.writeFileSync(jpath, JSON.stringify(out, null, 1) + "\n", "utf8");

  const rows = out.map((r) =>
    `["${r.pref}","${r.city}",[${r.census.join(",")}],[${r.juki.join(",")}],[${r.jukiDate.map((d) => `"${d}"`).join(",")}]]`
  );
  const htmlPath = path.join(ROOT, "index.html");
  const html = fs.readFileSync(htmlPath, "utf8");
  if (!/const NATIONAL=\[[\s\S]*?\n\];/.test(html)) throw new Error("index.html の const NATIONAL が見つからない");
  const next = html.replace(/const NATIONAL=\[[\s\S]*?\n\];/, `const NATIONAL=[\n${rows.join(",\n")}\n];`);
  fs.writeFileSync(htmlPath, next, "utf8");

  // students.html は national.json の住基配列をそのまま使う（build_students.py と同じ形）
  const sPath = path.join(ROOT, "data", "students.js");
  const src = fs.readFileSync(sPath, "utf8");
  const students = vm.runInNewContext(src + "\nSTUDENTS;", {});
  for (const r of students) {
    const n = out.find((x) => x.pref === r[0] && x.city === r[1]);
    if (!n) throw new Error(`students.js に対応する地点がない: ${r[0]}${r[1]}`);
    r[3] = n.juki;
  }
  const header = src.split("const STUDENTS=")[0]
    .replace(/住基\[[^\]]*\]/,
      "住基[2011-03-31,2015/2020/2025の9月末・10月1日（未公表は翌年1/1）]");
  const js = header + "const STUDENTS=[\n" +
    students.map((r) => JSON.stringify(r)).join(",\n") + "\n];\n";
  fs.writeFileSync(sPath, js, "utf8");

  console.log(`updated ${changed} values / 47 cities`);
  console.log("wrote data/national.json, index.html NATIONAL, data/students.js");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
